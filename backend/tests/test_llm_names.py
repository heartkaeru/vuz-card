import pytest

from app.services.llm.names import person_name_in_quote


@pytest.mark.parametrize("name,quote", [
    ("Иванов Иван Иванович", "Рабочая почта Иванова Ивана Ивановича: person@example.org"),
    ("Иванов Иван Иванович", "Обратитесь к Иванову Ивану Ивановичу."),
    ("Иванов Иван Иванович", "Встреча с Ивановым Иваном Ивановичем."),
    ("Кудинова Наталья Францевна", "Кудиновой Наталье Францевне направлено письмо."),
    ("Шмидт Александр Федорович", "Приём Шмидта Александра Фёдоровича."),
    ("Иванов Иван Иванович", "ИВАНОВ ИВАН ИВАНОВИЧ — ректор."),
])
def test_full_names_match_known_case_forms(name, quote):
    assert person_name_in_quote(name, quote)


@pytest.mark.parametrize("name,quote", [
    ("Иванов Иван Иванович", "Иванова Ивана Петровича, телефон."),
    ("Иванов Иван Иванович", "Иванова Петра Ивановича, телефон."),
    ("Иванов Иван Иванович", "Иванов Сергей Иванович, телефон."),
    ("Иванов Иван Иванович", "Иванов И. И., телефон."),
    ("Иванов И. И.", "Иванов Иван Иванович, телефон."),
    ("Иванов Иван Иванович", "Телефон приёмной ректора."),
    ("Иванов Иван Иванович", "Псевдоиванов Иван Иванович, телефон."),
    ("Иванов Иван Иванович", "Иван Иванович Иванов, телефон."),
    ("Кудинова Наталья Францевна", "Кудиновой Наталии Францевне, телефон."),
    ("Иванов Иван Иванович", "Иванова Иван Иванович, телефон."),
])
def test_similar_names_initials_and_mixed_cases_do_not_match(name, quote):
    assert not person_name_in_quote(name, quote)
